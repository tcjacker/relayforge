if (new URLSearchParams(location.search).get('language') === 'en') {
  document.documentElement.lang = 'en';
  var staticText = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (staticText.nextNode()) {
    var node = staticText.currentNode;
    // 侧栏的标签很窄，个别词要用缩写（data-en），不能和别处共用同一个译文
    var english = node.parentNode && node.parentNode.dataset && node.parentNode.dataset.en || staticEnglish[node.data.trim()];
    if (typeof english === 'string') node.data = node.data.replace(node.data.trim(), english);
  }
  var translatedAttributes = ['title', 'aria-label', 'placeholder', 'alt'];
  document.querySelectorAll(translatedAttributes.map(function (name) { return '[' + name + ']'; }).join(',')).forEach(function (element) {
    translatedAttributes.forEach(function (name) {
      var english = staticEnglish[element.getAttribute(name)];
      if (typeof english === 'string') element.setAttribute(name, english);
    });
  });
}
